fn budget() -> Budget {
    Budget {
        remaining: 4096,
        reader: ReaderBudget::try_from(4096).unwrap(),
        depth: 0,
        maximum_depth: 1024,
    }
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

#[test]
fn canonical_examples_keep_the_4_0_0_archive() {
    for (text, expected) in SAMPLES {
        let archived = if let Ok(query) =
            Potential::<Query>::from(text.to_string()).actualize(&mut budget())
        {
            hex(query.signalize().unwrap().bytes())
        } else {
            let response = Potential::<Response>::from(text.to_string())
                .actualize(&mut budget())
                .expect("a canonical example reads as a Query or a Response");
            hex(response.signalize().unwrap().bytes())
        };
        assert_eq!(archived, expected, "{text}");
    }
}
