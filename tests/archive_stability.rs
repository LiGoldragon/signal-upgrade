//! The archive of every canonical example is the archive 4.0.0 wrote (protos 0.31 cohort):
//! bytes captured from the 4.0.0 build, compared with the bytes this build writes.
#![cfg(feature = "datom")]
use datom_codec::{Actualizing, Budget, Potential};
use protos::ReaderBudget;
use signal_upgrade::{ByteViewable, Query, Response, Signalizable};

